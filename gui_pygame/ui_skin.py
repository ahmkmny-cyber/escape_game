"""Horror UI skin sliced from assets/ui_horror/FreeHorrorUi.png.

Boxes were detected by alpha analysis:
  panel_big   96x60  (136,4)-(232,64)
  panel_small 64x76  (128,132)-(192,208)
  buttons     52x16  2 cols x 4 rows (normal / variants)
  buttons_sm  48x16, 32x16
  icons       14-28px
Hover/pressed states are generated by tinting (sheet ships one state).
"""
import pygame
from . import config

BASE = config.BASE_DIR / "assets" / "ui_horror"

BTN_GRID = [(6 + c * 64, 138 + r * 32, 58, 154 - 138) for r in range(4) for c in range(2)]
# actual boxes: (6,138,58,154),(70,138,122,154),(6,170,58,186),(70,170,122,186),...
BTN_BOXES = [
    (6, 138, 58, 154), (70, 138, 122, 154),
    (6, 170, 58, 186), (70, 170, 122, 186),
    (6, 202, 58, 218), (70, 202, 122, 218),
    (6, 234, 58, 250), (70, 234, 122, 250),
]
PANEL_BIG = (136, 4, 232, 64)
PANEL_SMALL = (128, 132, 192, 208)

# Icon atlas order == contact_icons.png numbering (0-31).
# 0-23: FreeDemo grid (x in 2,18,34,50,68,84,100,116 x y in 2,18,34, 16x16)
# 24-31: horror pictograms.
# If a default looks wrong on the sheet, change the number here only.
ICON_MAP = {"clock": 0, "hint": 1, "back": 2}

_DEMO_XS = (2, 18, 34, 50, 68, 84, 100, 116)
_DEMO_YS = (2, 18, 34)
_HORROR_BOXES = [
    (130, 66, 158, 96), (166, 70, 186, 92),
    (106, 106, 122, 122), (136, 106, 154, 120),
    (168, 106, 186, 120), (200, 106, 218, 120),
    (8, 106, 56, 122), (66, 106, 98, 122),
]


def _icon_boxes():
    boxes = [("demo", x, y, 16, 16) for y in _DEMO_YS for x in _DEMO_XS]
    for (x0, y0, x1, y1) in _HORROR_BOXES:
        boxes.append(("horror", x0, y0, x1 - x0, y1 - y0))
    return boxes

_cache = {}


def sheet():
    if "sheet" not in _cache:
        _cache["sheet"] = pygame.image.load(str(BASE / "FreeHorrorUi.png")).convert_alpha()
    return _cache["sheet"]


def demo_sheet():
    if "demo" not in _cache:
        _cache["demo"] = pygame.image.load(str(BASE / "FreeDemo.png")).convert_alpha()
    return _cache["demo"]


def icon(name, size=28):
    """Single icon by logical name (see ICON_MAP). Returns None if missing."""
    try:
        idx = ICON_MAP[name]
        kind, x, y, w, h = _icon_boxes()[idx]
        img = demo_sheet() if kind == "demo" else sheet()
        return pygame.transform.smoothscale(img.subsurface((x, y, w, h)).copy(), (size, size))
    except Exception:
        return None


def crop(box):
    x0, y0, x1, y1 = box
    return sheet().subsurface((x0, y0, x1 - x0, y1 - y0)).copy()


def tint(surf, color, alpha=70):
    s = surf.copy()
    m = pygame.Surface(s.get_size(), pygame.SRCALPHA)
    m.fill((*color, alpha))
    s.blit(m, (0, 0))
    return s


def btn_images():
    if "btn" not in _cache:
        normal = crop(BTN_BOXES[0])
        _cache["btn"] = {
            "normal": normal,
            "hover": tint(normal, (255, 60, 60), 60),
            "pressed": tint(normal, (0, 0, 0), 90),
            "alt": crop(BTN_BOXES[1]),
        }
    return _cache["btn"]


def panel_big():
    if "panel" not in _cache:
        _cache["panel"] = crop(PANEL_BIG)
    return _cache["panel"]


def nine_slice(surf, rect, margin=12):
    """Draw surf stretched as 9-slice into rect (keeps corners crisp)."""
    W, H = surf.get_size()
    m = min(margin, W // 3, H // 3)
    x, y, w, h = rect
    patches = [
        ((0, 0, m, m), (x, y, m, m)),
        ((W - m, 0, m, m), (x + w - m, y, m, m)),
        ((0, H - m, m, m), (x, y + h - m, m, m)),
        ((W - m, H - m, m, m), (x + w - m, y + h - m, m, m)),
        ((m, 0, W - 2 * m, m), (x + m, y, w - 2 * m, m)),
        ((m, H - m, W - 2 * m, m), (x + m, y + h - m, w - 2 * m, m)),
        ((0, m, m, H - 2 * m), (x, y + m, m, h - 2 * m)),
        ((W - m, m, m, H - 2 * m), (x + w - m, y + m, m, h - 2 * m)),
        ((m, m, W - 2 * m, H - 2 * m), (x + m, y + m, w - 2 * m, h - 2 * m)),
    ]
    out = []
    for (sx, sy, sw, sh), (dx, dy, dw, dh) in patches:
        if sw <= 0 or sh <= 0 or dw <= 0 or dh <= 0:
            continue
        p = pygame.transform.smoothscale(surf.subsurface((sx, sy, sw, sh)), (dw, dh))
        out.append((p, (dx, dy)))
    return out
